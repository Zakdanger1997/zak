#!/usr/bin/env python3
"""Extract the "Load characteristics of gearboxes" list from the YP catalogue text.

Usage: pdftotext -layout YP-Katalog-2026-Rev.02.pdf yp.txt && apps.py yp.txt data/applications.js
"""
import re,json
import sys
lines=open(sys.argv[1],encoding='utf-8',errors='replace').read().replace('�','i').split('\n')
item=re.compile(r'^(.*?)\s{2,}([UMH])\s{2,}(.*?)\s{2,}([UMH])(\s{2,}.*)?$')
cats=[];cur=None
def is_item(s):
    m=item.match(s.rstrip()); return m if (m and m.group(2)==m.group(4)) else None
for idx,l in enumerate(lines):
    s=l.strip()
    if not s: continue
    m=is_item(l)
    if m:
        if cur is None:
            cur={'tr':'Diğer','en':'Other','items':[]}; cats.append(cur)
        cur['items'].append({'tr':m.group(1).strip(),'en':m.group(3).strip(),'cls':m.group(2)})
        continue
    # header candidate: next non-empty line is an item
    nxt=next((x for x in lines[idx+1:idx+4] if x.strip()),'')
    if is_item(nxt) and not re.search(r'\d',s) and len(s)<120:
        parts=[p.strip() for p in re.split(r'\s{3,}',s) if p.strip()]
        cur={'tr':parts[0],'en':parts[1] if len(parts)>1 else parts[0],'items':[]}
        cats.append(cur)
    elif cur is not None and cur['items']:
        cur=None
# merge duplicate categories (same tr), dedupe items
out={}
for c in cats:
    if not c['items']: continue
    k=c['tr']
    o=out.setdefault(k,{'tr':c['tr'],'en':c['en'],'items':[]})
    seen={i['tr'] for i in o['items']}
    for i in c['items']:
        if i['tr'] not in seen: o['items'].append(i); seen.add(i['tr'])
cats=list(out.values())
print('CATEGORIES',len(cats),'ITEMS',sum(len(c['items']) for c in cats))
for c in cats: print(f"- {c['tr']} / {c['en']} ({len(c['items'])}): "+'; '.join(f"{i['tr']}[{i['cls']}]" for i in c['items'])[:300])

# ---- clean-up for the app ----
def norm(s):
    s=s.replace('̇','').replace('i ','i') if 'i̇ ' in s or 'i ' in s and re.search(r'[A-ZÇĞİÖŞÜa-zçğıöşü]i [a-zçğıöşü]',s) else s
    return re.sub(r'\s+',' ',s).strip()
clean=[]
for c in cats:
    tr,en=norm(c['tr']),norm(c['en'])
    if tr=='Diğer': tr,en='Kaldırma ve İletme Tesisleri','Conveyors and Hoisting'
    if tr.startswith('Redüktör Yükleme'): tr,en='Metal İşleme Makinaları','Metal Working Machines'
    if 'ordering' in en.lower(): continue
    items=[{'tr':norm(i['tr']),'en':norm(i['en']),'cls':i['cls']} for i in c['items'] if i['tr'].strip() and i['en'].strip()]
    if items: clean.append({'tr':tr,'en':en,'items':items})
print('\nCLEAN',len(clean),sum(len(c['items']) for c in clean))
for c in clean: print(' ',c['tr'],'/',c['en'],len(c['items']))
open(sys.argv[2],'w',encoding='utf-8').write('/* generated by tools/apps.py from the i.Mak YP catalogue "Load characteristics of gearboxes" table */\nwindow.IMAK_APPLICATIONS = '+json.dumps(clean,ensure_ascii=False)+';\n')
